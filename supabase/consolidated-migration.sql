-- Non-destructive: preserves existing asset and investigation records.
CREATE TABLE IF NOT EXISTS public.estates (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 name text NOT NULL,
 notes text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.collections (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 name text NOT NULL,
 description text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.collection_assets (
 collection_id bigint NOT NULL REFERENCES public.collections(id) ON DELETE CASCADE,
 asset_id bigint NOT NULL REFERENCES public.assets(id) ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(collection_id,asset_id)
);
CREATE TABLE IF NOT EXISTS public.parties (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 name text NOT NULL,
 party_type text NOT NULL DEFAULT 'person' CHECK (party_type IN ('person','organization','trust','estate','other')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.locations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 name text NOT NULL,
 description text NOT NULL DEFAULT '',
 home_id bigint REFERENCES public.homes(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.asset_relationships (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 parent_asset_id bigint NOT NULL REFERENCES public.assets(id) ON DELETE CASCADE,
 child_asset_id bigint NOT NULL REFERENCES public.assets(id) ON DELETE CASCADE,
 relationship text NOT NULL DEFAULT 'set_member',
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(parent_asset_id,child_asset_id,relationship),
 CHECK(parent_asset_id <> child_asset_id)
);
ALTER TABLE public.assets ADD COLUMN IF NOT EXISTS estate_id bigint REFERENCES public.estates(id) ON DELETE SET NULL;
ALTER TABLE public.assets ADD COLUMN IF NOT EXISTS location_id bigint REFERENCES public.locations(id) ON DELETE SET NULL;
ALTER TABLE public.assets ADD COLUMN IF NOT EXISTS home_id bigint REFERENCES public.homes(id) ON DELETE SET NULL;
ALTER TABLE public.assets ADD COLUMN IF NOT EXISTS room_id bigint REFERENCES public.rooms(id) ON DELETE SET NULL;
ALTER TABLE public.assets ADD COLUMN IF NOT EXISTS notes text NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS public.asset_party_roles (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id bigint NOT NULL REFERENCES public.assets(id) ON DELETE CASCADE,
 party_id bigint NOT NULL REFERENCES public.parties(id) ON DELETE CASCADE,
 role text NOT NULL CHECK(role IN ('owner','custodian','executor','beneficiary','other')),
 valid_from timestamptz NOT NULL DEFAULT now(),
 valid_to timestamptz,
 notes text NOT NULL DEFAULT '',
 CHECK(valid_to IS NULL OR valid_to >= valid_from)
);
CREATE INDEX IF NOT EXISTS asset_party_roles_asset_idx ON public.asset_party_roles(asset_id);
CREATE INDEX IF NOT EXISTS assets_estate_idx ON public.assets(estate_id);
CREATE INDEX IF NOT EXISTS collection_assets_asset_idx ON public.collection_assets(asset_id);
