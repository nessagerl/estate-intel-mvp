-- RELEASE 4: run ONCE in Supabase SQL editor before deploying this code.
-- Soft deletion is reversible. No automatic purge is installed; 30 days is a
-- recovery policy/UI period, NOT a scheduled hard-delete job.
ALTER TABLE public.assets ADD COLUMN IF NOT EXISTS deleted_at timestamptz;
ALTER TABLE public.investigations ADD COLUMN IF NOT EXISTS deleted_at timestamptz;
CREATE INDEX IF NOT EXISTS assets_active_user_idx ON public.assets(user_id,deleted_at);
CREATE INDEX IF NOT EXISTS investigations_active_user_idx ON public.investigations(user_id,deleted_at);
CREATE TABLE IF NOT EXISTS public.investigation_evidence (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 investigation_id bigint NOT NULL REFERENCES public.investigations(id) ON DELETE CASCADE,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 details text NOT NULL,
 condition text NOT NULL DEFAULT 'unknown',
 source text NOT NULL DEFAULT 'personal',
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.investigation_valuations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 investigation_id bigint NOT NULL REFERENCES public.investigations(id) ON DELETE CASCADE,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 valuation jsonb NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS investigation_evidence_lookup_idx ON public.investigation_evidence(investigation_id,created_at);
CREATE INDEX IF NOT EXISTS investigation_valuations_lookup_idx ON public.investigation_valuations(investigation_id,created_at DESC);
ALTER TABLE public.investigation_evidence ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.investigation_valuations ENABLE ROW LEVEL SECURITY;
-- Server uses service role; all API operations must check user ownership.
NOTIFY pgrst, 'reload schema';
