ALTER TABLE public.assets ADD COLUMN IF NOT EXISTS category text;
ALTER TABLE public.assets ADD COLUMN IF NOT EXISTS category_source text;
CREATE TABLE IF NOT EXISTS public.asset_tags (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id bigint NOT NULL REFERENCES public.assets(id) ON DELETE CASCADE,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
 source text NOT NULL DEFAULT 'user' CHECK (source IN ('user','ai')),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(asset_id,name)
);
CREATE TABLE IF NOT EXISTS public.asset_tag_rejections (
 asset_id bigint NOT NULL REFERENCES public.assets(id) ON DELETE CASCADE,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 name text NOT NULL,
 PRIMARY KEY(asset_id,name)
);
CREATE INDEX IF NOT EXISTS asset_tags_user_idx ON public.asset_tags(user_id);
CREATE INDEX IF NOT EXISTS asset_tags_asset_idx ON public.asset_tags(asset_id);
ALTER TABLE public.asset_tags ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.asset_tag_rejections ENABLE ROW LEVEL SECURITY;
